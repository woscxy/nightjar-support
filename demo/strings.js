  const requested = new URLSearchParams(location.search).get("lang") || navigator.language || "en";
  const lower = requested.toLowerCase();
  let key = "en";
  if (lower.startsWith("zh")) {
    key = /hant|tw|hk|mo/.test(lower) ? "zh-Hant" : "zh-Hans";
  } else if (DEMO_STRINGS[lower.slice(0, 2)]) {
    key = lower.slice(0, 2);
  }
  document.documentElement.lang = key;
  document.title = `${DEMO_STRINGS[key].text.title} · Wildlife Journal`;
  return DEMO_STRINGS[key];
